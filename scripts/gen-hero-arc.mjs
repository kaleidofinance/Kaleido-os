/**
 * Generates public/hero-arc.svg — the dotted dome across the foot of the landing
 * page hero.
 *
 * ---------------------------------------------------------------------------
 * What this script does and does not decide
 * ---------------------------------------------------------------------------
 * It decides nothing about the shape. Every constant that used to live here —
 * the box, the ring radii, the spacing, the falloff, the seed — moved to
 * src/app/(marketing)/_components/heroArcField.ts, which is also what the canvas
 * in HeroArc.tsx reads. Two renderers of one field cannot be allowed to hold two
 * copies of the geometry: the canvas fades in over this SVG, and a copied
 * constant that drifts by one shows up as the field twitching at the swap.
 *
 * So: to change the shape, edit that module and re-run this. What is left here is
 * the serialisation, and the two decisions that belong to the file format rather
 * than to the artwork — bucketing and colour, below.
 *
 * ---------------------------------------------------------------------------
 * Why a generated file and not a component
 * ---------------------------------------------------------------------------
 * The field is ~1100 dots. Emitted as JSX that is ~1100 React elements and ~44 KB
 * of extra HTML on a page that already ships 120 KB, re-serialised into the RSC
 * payload on every request, for artwork that never changes. Generated once and
 * committed, it is a cacheable static asset and costs the document nothing.
 *
 * That is still true now that a canvas draws the same field at runtime, because
 * the canvas cannot paint until it hydrates. This file is what is on screen for
 * the first frame, with JavaScript off, and for a visitor who asked for reduced
 * motion — see the layering note in HeroArc.module.css.
 *
 * ---------------------------------------------------------------------------
 * Running it
 * ---------------------------------------------------------------------------
 *   npm run gen:arc
 *
 * Run through `tsx` because the geometry module is TypeScript; that is already
 * how `gen:registry` imports from src/. Change a constant, re-run, commit the SVG.
 *
 * ---------------------------------------------------------------------------
 * Bucketing
 * ---------------------------------------------------------------------------
 * Resting alpha arrives already quantised to 8 levels, so the circles can be
 * grouped by level under one `fill-opacity` each and a dot costs
 * `<circle cx cy r/>` and nothing more. Eight levels is past the point the eye
 * separates them at this size, and it is about a third off the file.
 *
 * ---------------------------------------------------------------------------
 * Colour
 * ---------------------------------------------------------------------------
 * Every dot is white. The file is consumed as a CSS `mask-image`, so what is
 * being written here is an alpha channel and the paint comes from a token in
 * HeroArc.module.css — which is what lets one asset serve both themes. An <img>
 * or a background-image could not do that: an externally-referenced SVG is its
 * own document and inherits nothing, so the colour would be frozen at #fff and
 * invisible on the light theme.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import {
  ARC_W,
  ARC_H,
  ARC_ALPHA_MAX,
  ARC_OPACITY_STEPS,
  buildArcField,
} from "../src/app/(marketing)/_components/heroArcField.ts";

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "public",
  "hero-arc.svg",
);

const dots = buildArcField();

/** Circle markup indexed by quantised opacity. Bucket 0 is dropped upstream. */
const buckets = Array.from({ length: ARC_OPACITY_STEPS }, () => []);

for (const d of dots) {
  const bucket = Math.round((d.a / ARC_ALPHA_MAX) * (ARC_OPACITY_STEPS - 1));
  buckets[bucket].push(
    `<circle cx="${d.x.toFixed(1)}" cy="${d.y.toFixed(1)}" r="${d.r.toFixed(2)}"/>`,
  );
}

const groups = buckets
  .map((circles, i) => {
    if (circles.length === 0) return "";
    const o = ((i / (ARC_OPACITY_STEPS - 1)) * ARC_ALPHA_MAX).toFixed(3);
    return `<g fill-opacity="${o}">${circles.join("")}</g>`;
  })
  .filter(Boolean)
  .join("\n");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ARC_W} ${ARC_H}" fill="#fff" shape-rendering="geometricPrecision">
<!-- Generated by scripts/gen-hero-arc.mjs from the geometry in
     src/app/(marketing)/_components/heroArcField.ts. Do not hand-edit: change a
     constant there and re-run \`npm run gen:arc\`. Consumed as a CSS mask-image,
     so every dot is white and the colour lives in HeroArc.module.css. -->
${groups}
</svg>
`;

writeFileSync(OUT, svg);

console.log(
  `hero-arc.svg  ${dots.length} dots, ${(svg.length / 1024).toFixed(1)} KB`,
);
